/**
 * Sign in, with one retry.
 *
 * Signing in hashes a password with scrypt, deliberately slowly, and then reads
 * the user row from a SQLite file four applications share. Under contention that
 * occasionally passed 30 seconds, and a single slow sign-in took every assertion
 * in the section with it — reported honestly as NOT RUN, but telling nobody
 * anything about the product.
 *
 * The retry is for the environment, not for the product: a sign-in that fails
 * twice still fails the section, and nothing about what is being measured is
 * softened.
 */
async function signIn(page, email, base = BASE) {
  let lastErr = null
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      await page.goto(`${base}/login`, { waitUntil: 'domcontentloaded' })
      await page.locator('input[type="email"], input[name="email"]').first().fill(email)
      await page.locator('input[type="password"], input[name="password"]').first().fill(PASSWORD)
      await page.locator('button[type="submit"]').first().click()
      await page.waitForURL(u => !u.pathname.startsWith('/login'), { timeout: 60_000 })
      return
    } catch (err) {
      lastErr = err
    }
  }
  throw lastErr
}

