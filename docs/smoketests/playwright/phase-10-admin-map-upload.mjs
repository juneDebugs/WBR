/**
 * Wait for the participant map list to satisfy `predicate`, and report how long
 * it took.
 *
 * ── Why this polls instead of reading once ───────────────────────────────────
 *
 * A writer awaits the participant app's answer to the cache invalidation before
 * it responds, so by the time a write returns, the tag HAS been cleared. Measured
 * during Phase 10's review cycle: a read issued immediately afterwards still
 * occasionally returned the old list. Clearing a tag is not synchronous with
 * respect to a read that follows in the same millisecond.
 *
 * Reading once and demanding the new value therefore asserts something the
 * product never promised — instantaneous propagation — and fails at random. What
 * the criterion actually means is that a saved change reaches delegates promptly,
 * with nobody clearing anything, as against the five-minute window it replaces.
 *
 * So this measures instead. The delay is printed on every call and the caller
 * asserts against a bound. A regression that put propagation back inside the
 * cache window fails this; a few hundred milliseconds does not.
 */
const PROPAGATION_LIMIT_MS = 5000

async function waitForViewer(predicate) {
  const started = Date.now()
  let maps = null
  while (Date.now() - started < PROPAGATION_LIMIT_MS) {
    const res = await page.request.get(`${BASE}/api/data/map`)
    if (res.status() === 200) {
      const body = await res.json()
      maps = body.maps ?? []
      if (predicate(maps)) return { ok: true, ms: Date.now() - started, maps }
    }
    await page.waitForTimeout(100)
  }
  return { ok: false, ms: Date.now() - started, maps }
}

