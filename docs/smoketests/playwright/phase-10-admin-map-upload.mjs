//
//   node docs/smoketests/playwright/phase-10-admin-map-upload.mjs
//
// Needs the participant app on 3001, the admin app on 3000, and the sponsor
// portal on 3003. Exits non-zero on any failure.
//
// The sponsor portal became a prerequisite on 2026-08-02: section 8 now checks
// that a representative editing their OWN company in that portal reaches the
// participant viewer. If the portal is not running, those two assertions are
// reported as failures with the reason, never quietly skipped.
//
// ── Slice 1: an uploaded map's picture is served from its own address ────────
//
// Finding F-14. GET /api/data/map returns every map for the conference in one
// response. An organizer's upload writes the picture into the imageUrl column
// as a base64 data URL, so without this change every uploaded picture would
// travel in full, for every map, on every visit to the map screen — even though
// a delegate looks at one map at a time. Measured: the three seeded pictures are
// 98,614 bytes on disk and roughly 131,000 as base64 text, and that is the floor
// rather than the ceiling once real venue plans replace line drawings.
//
// The response instead carries a short string for every map: a file path for a
// seeded one, /api/data/map/<id>/image for an uploaded one. That address decodes
// and serves the bytes.
//
// ── How this is proved, and why not by reading the code ──────────────────────
//
// The plan's criterion requires measuring the response body and searching it,
// not inspecting the implementation. So this file asks the running app for the
// map list over HTTP and searches the body it actually returns for the fixture's
// own base64 payload. A check that read the source could pass while the running
// app served something else.
//
// The search is for a 64-character slice of THIS FIXTURE's base64, not for the
// string "data:". Searching for "data:" would also match an unrelated field —
// a sponsor logo stored as a data URL, say — and fail for a reason that has
// nothing to do with maps. A precise anchor fails only when the real defect is
// present.
//
// ── A deliberate divergence from the precedent this follows ──────────────────
//
// F-14 says to copy apps/web/app/api/data/speakers/route.ts, which substitutes
// /api/speakers/<id>/photo for any stored value beginning "data:". That is the
// pattern for the substitution. Its backing address at
// apps/web/app/api/speakers/[id]/photo/route.ts is NOT the pattern for access:
// it never calls getToken, so anyone holding an id can read the picture.
//
// Copying that would put the venue's floor plans on an unauthenticated address
// while /api/data/map itself refuses both a signed-out visitor and a delegate
// with an incomplete profile. Sections 4 and 5 below assert the image address
// refuses each of them, so the picture is exactly as protected as the data that
// points at it.

