section('Cleanup')
{
  // ── Order matters here, and the first version of this file got it wrong ────
  //
  // Deleting the fixture map is not enough. The map read is cached for 300
  // seconds under 'floor-plan', and this script populated that cache with the
  // fixture present. Removing the row without clearing the cache leaves the app
  // serving a map that no longer exists, for up to five minutes, to whatever
  // runs next.
  //
  // Measured: with that step missing, Phase 8's suite immediately afterwards
  // found 4 maps instead of 3 and fell from 93 assertions to 27 — its switcher
  // section threw on a map whose row was gone. A suite that leaves a poisoned
  // cache is worse than one that leaves rows behind, because rows can be seen in
  // the database and the cache cannot.
  //
  // So: remove the map, clear the cache, then PROVE the app is back to what it
  // was, while the delegate is still signed in. Deleting the accounts comes last
  // because that verification needs one.
  // Markers first: a marker whose map is deleted goes with it, but a marker left
  // by a run that failed before its map was created would outlive this script.
  db.prepare(`DELETE FROM Pin WHERE id LIKE 'phase10-%'`).run()
  db.prepare(`DELETE FROM Sponsor WHERE id LIKE 'phase10-%'`).run()
  db.prepare(CLEANUP_MAPS).run()
  // Maps created through the upload handler carry database-generated ids, so the
  // prefix delete above does not reach them. Removed by name as well, in case a
  // run failed between creating one and recording its id.
  db.prepare(`DELETE FROM VenueMap WHERE name LIKE 'Phase 10 %'`).run()
  for (const id of createdMapIds) db.prepare(`DELETE FROM VenueMap WHERE id = ?`).run(id)

  const cleared = await page.request.post(`${BASE}/api/revalidate`, {
    data: { secret: REVALIDATE_SECRET, tags: ['floor-plan'] },
  })
  yes(cleared.ok(), 'the floor-plan cache was cleared after the fixture was removed', `HTTP ${cleared.status()}`)

  const after = await page.request.get(`${BASE}/api/data/map`)
  if (after.status() === 200) {
    const body = await after.json()
    const ids = (body.maps ?? []).map(m => m.id)
    yes(
      ids.length === seededMaps.length && !ids.some(id => id.startsWith('phase10-')),
      'the app serves exactly the maps it served before this script ran',
      `now serving ${ids.length}: ${ids.join(', ')}`,
    )
  } else {
    notRun(['the app serves exactly the maps it served before this script ran'], `the map list answered HTTP ${after.status()}`)
  }

  db.prepare(CLEANUP_USERS).run()
  const usersLeft = db.prepare(`SELECT COUNT(*) AS n FROM User WHERE id LIKE 'phase10-%'`).get().n
  const mapsLeft = db.prepare(`SELECT COUNT(*) AS n FROM VenueMap WHERE id LIKE 'phase10-%'`).get().n
  yes(usersLeft === 0, 'the disposable accounts were removed', `${usersLeft} left`)
  yes(mapsLeft === 0, 'the fixture map was removed', `${mapsLeft} left`)
}

