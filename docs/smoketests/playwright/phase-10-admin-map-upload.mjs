// ── 12. The map updates in front of a delegate who does nothing ──────────────
//
// The point of the push. Everything above proves a change reaches the SERVER
// promptly; none of it proves a phone already showing the map notices. Before
// this, it did not: the browser holds its own copy for five minutes and has no
// reason to ask again, so a delegate watching the screen saw nothing at all.
//
// The strong form of this check is a real browser sitting on the map screen,
// untouched, while an organizer makes a change through the admin app.

section('12. A delegate watching the map sees a change without touching anything')
{
  const LABELS = [
    'the stream refuses a signed-out visitor',
    'the stream refuses a delegate with an incomplete profile',
    'the phone opens a connection to be told about changes',
    'a delegate on the map screen sees a new map appear without touching the phone',
    'it arrived by the push rather than by the safety net',
  ]

  if (!adminReady) {
    notRun(LABELS, `could not sign in to the admin app — ${adminSignInError}`)
  } else {
    // Gated exactly like the data it announces. Leaking WHEN an organizer is
    // working is less serious than leaking what changed, and still nobody's
    // business.
    {
      const anon = await browser.newContext()
      const res = await anon.request.get(`${BASE}/api/data/map/stream`)
      yes(res.status() === 401 || res.status() === 403, 'the stream refuses a signed-out visitor', `got HTTP ${res.status()}`)
      await anon.close()
    }
    {
      const other = await browser.newContext()
      const otherPage = await other.newPage()
      await signIn(otherPage, INCOMPLETE_EMAIL)
      const res = await otherPage.request.get(`${BASE}/api/data/map/stream`)
      yes(res.status() === 403, 'the stream refuses a delegate with an incomplete profile', `got HTTP ${res.status()}`)
      await other.close()
    }

    // A real delegate, on the real screen, in a browser that is then left alone.
    const watcher = await browser.newContext()
    const watcherPage = await watcher.newPage()
    await signIn(watcherPage, COMPLETE_EMAIL)

    // ── Wait for the CONNECTION, not just for the page ──────────────────────
    //
    // The first version of this waited for [data-testid="floor-plan"], which is
    // also on the loading and error states. So it proceeded while the screen was
    // still loading, uploaded before the browser had opened its stream, and the
    // push reached nobody. The screen then sat on old data until the 30-second
    // safety net — past the 20-second window — and it looked like the push was
    // broken when the push had never been given anything to deliver to.
    //
    // Two waits now. The switcher only renders once the map data has arrived, so
    // it proves the screen is genuinely up. The request waiter is armed BEFORE
    // navigating, so it cannot miss a connection opened early.
    const streamOpened = watcherPage
      .waitForRequest(r => r.url().includes('/api/data/map/stream'), { timeout: 30_000 })
      .catch(() => null)

    await watcherPage.goto(`${BASE}/map`, { waitUntil: 'domcontentloaded' })

    const switcher = watcherPage.locator('[data-testid="map-switcher"]').first()
    await switcher.waitFor({ state: 'visible', timeout: 30_000 }).catch(() => {})
    const connected = await streamOpened
    yes(!!connected, 'the phone opens a connection to be told about changes', 'no request to the stream was made')

    const before = await watcherPage.getByText('Phase 10 Live Screen Map').count()

    // Nothing touches this browser from here on.
    const started = Date.now()
    const res = await adminPage.request.post(`${ADMIN_BASE}/api/floor-plan/maps`, {
      data: { name: 'Phase 10 Live Screen Map', imageDataUrl: FIXTURE_DATA_URL },
      failOnStatusCode: false,
    })
    const row = db.prepare(`SELECT id FROM VenueMap WHERE name = ?`).get('Phase 10 Live Screen Map')
    if (row) createdMapIds.push(row.id)

    // Waiting for the NAME to appear on screen, not for a network call. This is
    // what a person in the room would see.
    let appeared = false
    let ms = 0
    if (res.status() === 201) {
      try {
        await watcherPage.getByText('Phase 10 Live Screen Map').first().waitFor({ state: 'visible', timeout: 20_000 })
        appeared = true
      } catch {
        appeared = false
      }
      ms = Date.now() - started
    }

    yes(
      before === 0 && res.status() === 201 && appeared,
      'a delegate on the map screen sees a new map appear without touching the phone',
      `upload HTTP ${res.status()}; after ${ms}ms the screen ${appeared ? 'showed it' : 'had not changed'}`,
    )
    if (appeared) console.log(`    measured: appeared on an untouched screen in ${ms}ms`)

    // The safety net alone would also make it appear, just slowly. Recording the
    // delay is what distinguishes the push working from the timer rescuing it:
    // the timer runs every 30 seconds, so anything under a second is the push.
    if (appeared) {
      yes(ms < 5_000, 'it arrived by the push rather than by the safety net',
        `took ${ms}ms — over 5s means the push did not fire and the 30s timer did the work`)
    } else {
      notRun(['it arrived by the push rather than by the safety net'], 'nothing appeared on the screen')
    }

    await watcher.close()
  }
}


