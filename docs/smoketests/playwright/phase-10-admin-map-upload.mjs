/**
 * A PNG whose header declares a size, followed by nothing in particular.
 *
 * The upload handler reads a picture's dimensions from its header, because this
 * repository has no image library and adding one is not in Phase 10. A header is
 * therefore exactly as much as the handler ever looks at, so a header is exactly
 * what this needs to provide. Building a real 3000-pixel image would test the
 * same code path through more machinery.
 */
function pngWithDeclaredSize(width, height) {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  const ihdr = Buffer.alloc(25)
  ihdr.writeUInt32BE(13, 0)
  ihdr.write('IHDR', 4)
  ihdr.writeUInt32BE(width, 8)
  ihdr.writeUInt32BE(height, 12)
  ihdr[16] = 8 // bit depth
  ihdr[17] = 6 // colour type: RGBA
  return Buffer.concat([signature, ihdr, Buffer.alloc(64)])
}

